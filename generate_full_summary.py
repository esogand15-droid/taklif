import os
from PIL import Image, ImageDraw, ImageFont
import arabic_reshaper
from bidi.algorithm import get_display

BASE = '/home/user/taklif'
FDIR = os.path.join(BASE, 'fonts_vazir')
OUT  = os.path.join(BASE, 'output')
os.makedirs(OUT, exist_ok=True)

W, H = 2480, 3508
ML, MR, MT, MB = 280, 280, 240, 240
TW = W - ML - MR
S_BODY = 40
S_TITLE = 54
S_SUB = 46
S_HDR = 48
LH = 1.75
C_BLACK = (30, 30, 30)
C_TITLE = (0, 60, 140)
C_VERSE = (0, 100, 60)
C_DEF   = (0, 70, 150)
C_LINE  = (0, 60, 140)
C_PAPER = (255, 255, 255)
C_FOOT  = (160, 160, 160)

def rp(text):
    if not text or not text.strip(): return text
    return get_display(arabic_reshaper.reshape(text))

def font(size, w='Regular'):
    return ImageFont.truetype(os.path.join(FDIR, f'Vazirmatn-{w}.ttf'), size)

def wrap(text, f, max_w, draw):
    words = text.split()
    lines, cur = [], ""
    for w in words:
        test = cur + (" " if cur else "") + w
        bb = draw.textbbox((0, 0), rp(test), font=f)
        if bb[2] - bb[0] <= max_w: cur = test
        else:
            if cur: lines.append(cur)
            cur = w
    if cur: lines.append(cur)
    return lines

def tr(draw, txt, xr, y, f, color):
    d = rp(txt); bb = draw.textbbox((0, 0), d, font=f)
    draw.text((xr - (bb[2] - bb[0]), y), d, font=f, fill=color)

def tc(draw, txt, y, f, color):
    d = rp(txt); bb = draw.textbbox((0, 0), d, font=f)
    draw.text(((W - (bb[2] - bb[0])) // 2, y), d, font=f, fill=color)

def render_page(lines, page_num):
    img = Image.new('RGB', (W, H), C_PAPER)
    draw = ImageDraw.Draw(img)
    y, xr = MT, W - MR
    for item in lines:
        txt, sty, sp = item.get('t',''), item.get('s','body'), item.get('sp',0)
        if not txt.strip():
            y += sp if sp else 25; continue
        if sty == 'title':
            tc(draw, txt, y, font(S_TITLE,'Bold'), C_TITLE); y += int(S_TITLE*1.6)
        elif sty == 'sub':
            tr(draw, txt, xr, y, font(S_SUB,'Bold'), C_TITLE); y += int(S_SUB*1.5)
        elif sty == 'hdr':
            tr(draw, txt, xr, y, font(S_HDR,'Bold'), C_TITLE)
            draw.line([(ML, y+int(S_HDR*1.2)), (xr, y+int(S_HDR*1.2))], fill=C_LINE, width=2)
            y += int(S_HDR*1.6)
        elif sty == 'verse':
            f = font(S_BODY+2,'Medium')
            for wl in wrap(txt, f, TW-160, draw):
                tr(draw, wl, xr-80, y, f, C_VERSE); y += int((S_BODY+2)*LH)
            y += 10
        elif sty == 'def':
            tr(draw, txt, xr, y, font(S_BODY,'Bold'), C_DEF); y += int(S_BODY*1.4)
        else:
            f = font(S_BODY)
            for wl in wrap(txt, f, TW, draw):
                tr(draw, wl, xr, y, f, C_BLACK); y += int(S_BODY*LH)
        if sp: y += sp
    tc(draw, f'{page_num}', H-MB+50, font(30), C_FOOT)
    return img

