#!/usr/bin/env python3
"""
Generate a 4-page A4 PDF summary of the chapter:
"تکالیف انسان در برابر خدا" from "تفسیر موضوعی قرآن کریم"
"""

from fpdf import FPDF
import arabic_reshaper
from bidi.algorithm import get_display
import os

# ===== Font paths =====
FONT_REGULAR = '/home/user/taklif/fonts_new/Mikhak-DS1-FD-Regular.ttf'
FONT_MEDIUM = '/home/user/taklif/fonts_new/Mikhak-DS1-FD-Medium.ttf'
FONT_BOLD = '/home/user/taklif/fonts_new/Mikhak-DS1-FD-Bold.ttf'

OUTPUT_DIR = '/home/user/taklif/output'
os.makedirs(OUTPUT_DIR, exist_ok=True)

def reshape_text(text):
    """Reshape Persian text for correct RTL display."""
    reshaped = arabic_reshaper.reshape(text)
    return get_display(reshaped)

class PersianPDF(FPDF):
    def __init__(self):
        super().__init__(orientation='P', unit='mm', format='A4')
        self.set_auto_page_break(auto=True, margin=20)
        
        # Add Persian fonts (FPDF2 only supports B/I styles, so use separate families)
        self.add_font('MikhakR', '', FONT_REGULAR)
        self.add_font('MikhakM', '', FONT_MEDIUM)
        self.add_font('MikhakB', '', FONT_BOLD)
    
    def header(self):
        pass
    
    def footer(self):
        self.set_y(-15)
        self.set_font('MikhakM', '', 9)
        self.set_text_color(120, 115, 105)
        page_num = self.page_no()
        self.cell(0, 10, reshape_text(f'— {page_num} —'), align='C')
    
    def add_title(self, text, size=16):
        self.set_font('MikhakB', '', size)
        self.set_text_color(10, 25, 120)
        self.cell(0, 10, reshape_text(text), align='C', new_x='LMARGIN', new_y='NEXT')
        self.ln(2)
    
    def add_subtitle(self, text, size=13):
        self.set_font('MikhakB', '', size)
        self.set_text_color(15, 35, 140)
        self.cell(0, 8, reshape_text(text), align='R', new_x='LMARGIN', new_y='NEXT')
        self.ln(1)
    
    def add_body(self, text, size=10.5):
        self.set_font('MikhakR', '', size)
        self.set_text_color(30, 30, 30)
        self.multi_cell(0, 6.5, reshape_text(text), align='R')
        self.ln(1)
    
    def add_bullet(self, text, size=10.5):
        self.set_font('MikhakR', '', size)
        self.set_text_color(30, 30, 30)
        self.multi_cell(0, 6.5, reshape_text(text), align='R')
        self.ln(0.5)
    
    def add_verse(self, text, size=11):
        self.set_font('MikhakM', '', size)
        self.set_text_color(20, 50, 130)
        self.set_x(self.l_margin + 10)
        self.multi_cell(self.w - self.l_margin - self.r_margin - 20, 7, reshape_text(text), align='R')
        self.ln(1)
    
    def add_definition(self, term, definition, size=10.5):
        self.set_font('MikhakB', '', size)
        self.set_text_color(10, 25, 120)
        self.cell(0, 7, reshape_text(term), align='R', new_x='LMARGIN', new_y='NEXT')
        self.set_font('MikhakR', '', size)
        self.set_text_color(30, 30, 30)
        self.multi_cell(0, 6.5, reshape_text(definition), align='R')
        self.ln(1)

